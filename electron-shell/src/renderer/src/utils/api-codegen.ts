// HELPERS
// ─────────────────────────────────────────────────────────────────────────────

interface BindingInfo {
  widgetId:      string
  interfaceId:   string
  fieldPath:     string
  targetProp:    string
  format:        string
  formatArg?:    string
  visibilityExpr?: string
  isListBinding?: boolean
}

function collectBindings(widgets: WidgetNode[]): BindingInfo[] {
  const out: BindingInfo[] = []
  for (const w of widgets) {
    if ((w as any).apiBinding?.interfaceId) {
      const b = (w as any).apiBinding
      out.push({ widgetId: w.id, interfaceId: b.interfaceId, fieldPath: b.fieldPath,
        targetProp: b.targetProp, format: b.format, formatArg: b.formatArg,
        visibilityExpr: b.visibilityExpr, isListBinding: b.isListBinding })
    }
  }
  return out
}

function buildAccessor(fieldPath: string, root: string, df: DataFile): string {
  // Converts "groups[].memberCount" → "data.groups.isNotEmpty ? data.groups.first.memberCount : null"
  const parts = fieldPath.split('.')
  let accessor = root
  for (const p of parts) {
    if (p.endsWith('[]')) {
      accessor += '.' + p.slice(0,-2)
    } else {
      accessor += '.' + p
    }
  }
  return accessor
}

function buildFormatCall(accessor: string, format: string, arg?: string): string {
  switch (format) {
    case 'currency':    return `AzUtils.formatCurrency(${accessor})`
    case 'percentage':  return `'\${(${accessor} as num).toStringAsFixed(1)}%'`
    case 'uppercase':   return `${accessor}.toString().toUpperCase()`
    case 'lowercase':   return `${accessor}.toString().toLowerCase()`
    case 'date':        return `AzUtils.formatDate(${accessor})`
    case 'dateTime':    return `AzUtils.formatDateTime(${accessor})`
    case 'truncate':    return `AzUtils.truncate(${accessor}.toString(), ${arg || 20})`
    default:            return `${accessor}`
  }
}

function dartType(f: SchemaField): string {
  const n = f.required ? '' : '?'
  switch (f.type) {
    case 'String':   return `String${n}`
    case 'int':      return `int${n}`
    case 'double':   return `double${n}`
    case 'bool':     return `bool${n}`
    case 'DateTime': return `DateTime${n}`
    case 'List':     return `List<${f.itemType || 'dynamic'}>${n}`
    case 'Object':   return `Map<String, dynamic>${n}`
    default:         return 'dynamic'
  }
}

function dartTypeNullable(f: SchemaField): string {
  return dartType({ ...f, required: false }).replace(/\?$/, '')
}

function jsonAccessor(f: SchemaField): string {
  const k = `'${f.name}'`
  const req = f.required
  switch (f.type) {
    case 'String':   return `json[${k}] as String${req ? '' : '?'}`
    case 'int':      return req ? `(json[${k}] as num).toInt()` : `json[${k}] != null ? (json[${k}] as num).toInt() : null`
    case 'double':   return req ? `(json[${k}] as num).toDouble()` : `json[${k}] != null ? (json[${k}] as num).toDouble() : null`
    case 'bool':     return `json[${k}] as bool${req ? '' : '? ?? false'}`
    case 'DateTime': return `DateTime.tryParse(json[${k}] as String? ?? '')`
    case 'List':     {
      const it = f.itemType || 'dynamic'
      const isPrimitive = ['String','int','double','bool'].includes(it)
      if (isPrimitive) return `(json[${k}] as List?)?.map((e) => e as ${it}).toList() ?? []`
      return `(json[${k}] as List?)?.map((e) => ${it}.fromJson(e as Map<String,dynamic>)).toList() ?? []`
    }
    case 'Object':   return `Map<String,dynamic>.from(json[${k}] as Map? ?? {})`
    default:         return `json[${k}]`
  }
}

function jsonSerializer(f: SchemaField): string {
  if (f.type === 'DateTime') return `${f.name}?.toIso8601String()`
  if (f.type === 'List' && f.itemType && !['String','int','double','bool'].includes(f.itemType))
    return `${f.name}${f.required?'':' ?? []'}.map((e) => e.toJson()).toList()`
  return f.name
}

function toSnakeCase(s: string): string {
  return s.replace(/([A-Z])/g, (_, l, i) => (i > 0 ? '_' : '') + l.toLowerCase())
    .replace(/^_/, '').replace(/__+/g, '_')
}

function capitalize(s: string): string {
  return s.charAt(0).toUpperCase() + s.slice(1)
}
