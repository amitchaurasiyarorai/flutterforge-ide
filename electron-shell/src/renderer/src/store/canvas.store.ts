function createDefaultProject(name: string, packageName: string): FlutterForgeProject {
  const welcomeScreenId = 'screen_welcome'
  const scaffoldId      = 'w_scaffold'
  const appBarId        = 'w_appbar'
  const bodyId          = 'w_body'
  const textId          = 'w_text'

  return {
    id:           uuidv4(),
    name,
    packageName,
    version:      '1.0.0',
    description:  'Generated by FlutterForge',
    initialRoute: '/welcome',
    screens: {
      [welcomeScreenId]: {
        id:           welcomeScreenId,
        name:         'WelcomeScreen',
        route:        '/welcome',
        title:        'Welcome',
        rootWidgetId: scaffoldId,
        widgets: {
          [scaffoldId]: {
            id:       scaffoldId,
            type:     'flutter.widgets.Scaffold' as WidgetType,
            props:    {},
            children: [appBarId, bodyId],
          },
          [appBarId]: {
            id:    appBarId,
            type:  'flutter.widgets.AppBar' as WidgetType,
            props: { title: name, centerTitle: true },
          },
          [bodyId]: {
            id:       bodyId,
            type:     'flutter.widgets.Center' as WidgetType,
            props:    {},
            children: [textId],
          },
          [textId]: {
            id:    textId,
            type:  'flutter.widgets.Text' as WidgetType,
            props: {
              data:  'Welcome to ' + name,
              style: { fontSize: 24, fontWeight: 'w500' },
            },
          },
        },
      },
    },
    services:       {},
    stateProviders: {},
    assets:         [],
    dependencies:   {},
    theme: {
      primaryColor:      { hex: '#6200EA' },
      secondaryColor:    { hex: '#03DAC6' },
      tertiaryColor:     { hex: '#EFB8C8' },
      errorColor:        { hex: '#B00020' },
      backgroundColor:   { hex: '#FFFBFE' },
      surfaceColor:      { hex: '#FFFBFE' },
      onPrimaryColor:    { hex: '#FFFFFF' },
      onSecondaryColor:  { hex: '#000000' },
      onBackgroundColor: { hex: '#1C1B1F' },
      onSurfaceColor:    { hex: '#1C1B1F' },
      onErrorColor:      { hex: '#FFFFFF' },
      fontFamily: 'Roboto',
      displayFontSize: 57, headlineFontSize: 32, titleFontSize: 22,
      bodyFontSize: 14, labelFontSize: 12,
      fontWeightBold: 700, fontWeightNormal: 400,
      borderRadiusSmall: 8, borderRadiusMedium: 12,
      borderRadiusLarge: 28, borderRadiusFull: 50,
      appBarElevation: 0, cardElevation: 2, buttonHeight: 48,
      inputBorderStyle: 'outline' as const,
      useMaterial3: true,
      brightness: 'system' as const,
    },
    createdAt: new Date().toISOString(),
    updatedAt: new Date().toISOString(),
    metadata: {
      targetPlatforms: ['android', 'ios', 'web'],
    },
  }
}

