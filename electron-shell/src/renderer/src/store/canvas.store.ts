import { create } from 'zustand'
import { immer } from 'zustand/middleware/immer'
import { subscribeWithSelector } from 'zustand/middleware'
import { v4 as uuidv4 } from 'uuid'
import type {
  FlutterForgeProject,
  ScreenDefinition,
  WidgetNode,
  WidgetType,
} from '../types/widget.schema'

// ─────────────────────────────────────────────────────────
// TYPES
// ─────────────────────────────────────────────────────────

export interface CanvasSelection {
  widgetIds: string[]
  screenId: string | null
}

export interface HistoryEntry {
  label: string
  screens: Record<string, ScreenDefinition>
}

export interface CanvasState {
  // Project
  project: FlutterForgeProject | null
  projectFilePath: string | null
  isDirty: boolean

  // Active screen
  activeScreenId: string | null

  // Selection
  selection: CanvasSelection

  // Undo/redo
  history: HistoryEntry[]
  historyIndex: number
  canUndo: boolean
  canRedo: boolean

  // UI state
  zoom: number
  gridEnabled: boolean
  snapToGrid: boolean
  gridSize: number
  showProperties: boolean
  showPalette: boolean
  showCopilot: boolean
  isGenerating: boolean
  generationProgress: string

  // Actions — Project
  setProject:         (project: FlutterForgeProject) => void
  newProject:         (name: string, packageName: string) => void
  updateProjectMeta:  (meta: { name?: string; packageName?: string; version?: string; description?: string }) => void
  setFilePath:        (path: string) => void
  markDirty:          () => void
  markClean:          () => void

  // Actions — Screen
  updateTheme:      (patch: Partial<import('../types/widget.schema').AppTheme>) => void
  addScreen:        (name: string, route: string) => string
  deleteScreen:     (screenId: string) => void
  // Asset actions
  addAsset:         (asset: import('../types/widget.schema').AssetDefinition) => void
  removeAsset:      (assetId: string) => void
  updateAsset:      (assetId: string, updates: Partial<import('../types/widget.schema').AssetDefinition>) => void
  setActiveScreen:  (screenId: string) => void
  updateScreen:     (screenId: string, updates: Partial<ScreenDefinition>) => void
  setScreenFromAI:  (screenId: string, screen: ScreenDefinition) => void

  // Actions — Navigation Designer
  setInitialRoute:      (route: string) => void
  setScreenNavPos:      (screenId: string, pos: { x: number; y: number }) => void
  addNavConnection:     (conn: Omit<import('../types/widget.schema').NavConnection, 'id'>) => string
  updateNavConnection:  (connId: string, updates: Partial<import('../types/widget.schema').NavConnection>) => void
  removeNavConnection:  (connId: string) => void

  // Actions — Widget
  addWidget:        (screenId: string, widget: Omit<WidgetNode, 'id'>, parentId?: string) => string
  updateWidget:     (screenId: string, widgetId: string, updates: Partial<WidgetNode>) => void
  deleteWidget:     (screenId: string, widgetId: string) => void
  moveWidget:       (screenId: string, widgetId: string, newParentId: string | null, index: number) => void
  reparentWidget:   (screenId: string, widgetId: string, newParentId: string) => void

  // Actions — Selection
  selectWidget:     (screenId: string, widgetId: string, multi?: boolean) => void
  selectWidgets:    (screenId: string, widgetIds: string[]) => void
  clearSelection:   () => void

  // Actions — History
  pushHistory:      (label: string) => void
  undo:             () => void
  redo:             () => void

  // Actions — Canvas UI
  setZoom:          (zoom: number) => void
  toggleGrid:       () => void
  toggleSnapToGrid: () => void
  togglePalette:    () => void
  toggleProperties: () => void
  toggleCopilot:    () => void
  setGenerating:    (generating: boolean, progress?: string) => void
}

